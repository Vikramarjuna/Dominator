const (
	convPreamble = `// Code generated by proto-gen. DO NOT EDIT.

package %s

import (
`
	knownTypes = "google.golang.org/protobuf/types/known/"
	pbAlias    = "pb"
	timeType   = "time.Time"
)

// convImports maps the package names used in the generated converters, apart
// from the proto and SRPC type packages, to their import paths.
var convImports = map[string]string{
	"durationpb":  knownTypes + "durationpb",
	"lib_grpc":    "github.com/Cloud-Foundations/Dominator/lib/grpc",
	"net":         "net",
	"tags":        "github.com/Cloud-Foundations/Dominator/lib/tags",
	"time":        "time",
	"timestamppb": knownTypes + "timestamppb",
}

// invalidFieldName matches the field and message names which protoc-gen-go
// changes when it makes the Go name, or which clash with a generated method, so
// the converters could not refer to them. It rejects a few safe names as well.
var invalidFieldName = regexp.MustCompile(`_|[0-9][a-z]|^(Descriptor|` +
	`ExtensionMap|ExtensionRangeArray|Marshal|ProtoMessage|ProtoReflect|` +
	`Reset|String|Unmarshal)$`)

// scalarGoTypes maps a proto scalar type to the Go type protoc-gen-go uses.
var scalarGoTypes = map[string]string{
	"bool":   "bool",
	"double": "float64",
	"float":  "float32",
	"int32":  "int32",
	"int64":  "int64",
	"string": "string",
	"uint32": "uint32",
	"uint64": "uint64",
}

// wellKnownConv describes the conversion of a Go type from another package.
type wellKnownConv struct {
	to      string // Proto value for the Go value %s.
	from    string // Go value for the proto value %s.
	fromErr bool   // The from expression also returns an error.
	imports []string
}

var wellKnownConvs = map[string]wellKnownConv{
	"net.HardwareAddr": {"%s.String()", "lib_grpc.StringToMAC(%s)", true,
		[]string{"lib_grpc"}},
	"net.IP": {"lib_grpc.IPToString(%s)", "lib_grpc.StringToIP(%s)", true,
		[]string{"lib_grpc"}},
	"tags.Tags": {"lib_grpc.TagsToMap(%s)", "lib_grpc.MapToTags(%s)", false,
		[]string{"lib_grpc"}},
	"time.Duration": {"durationpb.New(%s)", "%s.AsDuration()", false,
		[]string{"durationpb"}},
	timeType: {"timestamppb.New(%s)", "%s.AsTime()", false,
		[]string{"timestamppb"}},
}

type convConfig struct {
	GoPackage    string // Import path of the generated proto Go code.
	Package      string // Name of the Go package to write.
	TypesPackage string // Import path of the package of the SRPC types.
}

// direction holds what differs between converting to and from the proto form.
type direction struct {
	convert  func(dst, src string, expr ast.Expr, level int) ([]string, error)
	destType func(expr ast.Expr) (string, error) // Go type of the result.
	prefix   string                              // For temporary variables.
}

type convGenerator struct {
	from      direction
	imports   map[string]string // Import paths, by package name.
	mapper    *typeMapper
	messages  map[string]struct{} // Names of the generated messages.
	named     map[string]string   // Underlying types of non-struct types.
	to        direction
	typesName string // Package name of the SRPC types.
}

// generateConverters returns the text of the Go file which converts each
// message in infos between the SRPC type and the type generated from the
// .proto file. named is the result of scanNamedTypes. An error is returned if
// config is invalid or a field has a type which cannot be converted.
func generateConverters(config convConfig, infos []typeInfo,
	named map[string]string) (string, error) {
	if !identifierPattern.MatchString(config.Package) {
		return "", fmt.Errorf("invalid Go package name %q", config.Package)
	}
	if config.GoPackage == "" || config.TypesPackage == "" {
		return "", errors.New("empty Go package path")
	}
	if len(infos) < 1 {
		return "", errors.New("no @grpc types to generate")
	}
	typesName := path.Base(config.TypesPackage)
	_, clash := convImports[typesName]
	if !identifierPattern.MatchString(typesName) || clash ||
		slices.Contains([]string{pbAlias, "err", "in", "out"}, typesName) {
		return "", fmt.Errorf("cannot use package name %q for %s", typesName,
			config.TypesPackage)
	}
	messages := make(map[string]struct{}, len(infos))
	for _, info := range infos {
		if !token.IsExported(info.Name) || invalidFieldName.MatchString(
			info.Name) {
			return "", fmt.Errorf("message %s: name would be changed by "+
				"protoc-gen-go or is not exported", info.Name)
		}
		messages[info.Name] = struct{}{}
	}
	generator := &convGenerator{
		imports: map[string]string{
			pbAlias:   config.GoPackage,
			typesName: config.TypesPackage,
		},
		mapper:    newTypeMapper(messages, named),
		messages:  messages,
		named:     named,
		typesName: typesName,
	}
	generator.to = direction{generator.toProto, generator.pbType, "proto"}
	generator.from = direction{generator.fromProto, generator.srcType, "go"}
	var body bytes.Buffer
	for _, info := range infos {
		text, err := generator.messageFuncs(info)
		if err != nil {
			return "", err
		}
		body.WriteString("\n")
		body.WriteString(text)
	}
	var file bytes.Buffer
	fmt.Fprintf(&file, convPreamble, config.Package)
	file.WriteString(generator.importLines())
	file.WriteString(")\n")
	file.Write(body.Bytes())
	formatted, err := format.Source(file.Bytes())
	if err != nil {
		return "", fmt.Errorf("generated code is invalid: %w", err)
	}
	return string(formatted), nil
}

// importLines returns the import specs for the packages used, in groups for
// the standard library, other modules and Cloud-Foundations packages.
func (g *convGenerator) importLines() string {
	var groups [3][]string
	for _, name := range slices.Sorted(maps.Keys(g.imports)) {
		importPath := g.imports[name]
		spec := fmt.Sprintf("\t%q\n", importPath)
		if name == pbAlias || name == g.typesName || name == "lib_grpc" {
			spec = fmt.Sprintf("\t%s %q\n", name, importPath)
		}
		switch {
		case strings.HasPrefix(importPath, "github.com/Cloud-Foundations/"):
			groups[2] = append(groups[2], spec)
		case strings.Contains(strings.Split(importPath, "/")[0], "."):
			groups[1] = append(groups[1], spec)
		default:
			groups[0] = append(groups[0], spec)
		}
	}
	var lines []string
	for _, group := range groups {
		if len(group) > 0 {
			lines = append(lines, strings.Join(group, ""))
		}
	}
	return strings.Join(lines, "\n")
}

// needs records that the generated code uses the package called name, which
// must be one of convImports.
func (g *convGenerator) needs(name string) {
	g.imports[name] = convImports[name]
}

// messageFuncs returns the text of the two converter functions of a message.
// An error is returned if a field has a type that the .proto generator cannot
// map or that cannot be converted.
func (g *convGenerator) messageFuncs(info typeInfo) (string, error) {
	var from, to []string
	fieldNames := make(map[string]struct{}, len(info.Fields))
	for _, field := range info.Fields {
		fieldNames[field.Name] = struct{}{}
	}
	for _, field := range info.Fields {
		fieldErr := func(err error) error {
			return fmt.Errorf("message %s field %s: %w", info.Name,
				field.Name, err)
		}
		_, getterClash := fieldNames[strings.TrimPrefix(field.Name, "Get")]
		if !token.IsExported(field.Name) ||
			invalidFieldName.MatchString(field.Name) ||
			(getterClash && strings.HasPrefix(field.Name, "Get")) {
			return "", fieldErr(errors.New("name is not exported or would " +
				"be changed by protoc-gen-go"))
		}
		expr, err := parser.ParseExpr(field.GoType)
		if err != nil {
			return "", fieldErr(err)
		}
		if _, err := g.mapper.protoType(expr); err != nil {
			return "", fieldErr(err)
		}
		lines, err := g.toProto("out."+field.Name, "in."+field.Name, expr, 0)
		if err != nil {
			return "", fieldErr(err)
		}
		to = append(to, lines...)
		lines, err = g.fromProto("out."+field.Name,
			"in.Get"+field.Name+"()", expr, 0)
		if err != nil {
			return "", fieldErr(err)
		}
		from = append(from, lines...)
	}
	srcType := g.typesName + "." + info.Name
	var buffer bytes.Buffer
	fmt.Fprintf(&buffer, "// toProto%s returns the proto form of in, or nil "+
		"if in is nil.\n", info.Name)
	fmt.Fprintf(&buffer, "func toProto%s(in *%s) *pb.%s {\n", info.Name,
		srcType, info.Name)
	fmt.Fprintf(&buffer, "if in == nil {\nreturn nil\n}\nout := &pb.%s{}\n",
		info.Name)
	buffer.WriteString(strings.Join(to, "\n"))
	buffer.WriteString("\nreturn out\n}\n\n")
	fmt.Fprintf(&buffer, "// fromProto%s returns the SRPC form of in, which "+
		"is the zero value if in is nil.\n// It returns an error if a field "+
		"is invalid.\n", info.Name)
	fmt.Fprintf(&buffer, "func fromProto%s(in *pb.%s) (%s, error) {\n",
		info.Name, info.Name, srcType)
	fmt.Fprintf(&buffer, "var out %s\nvar err error\n", srcType)
	buffer.WriteString(strings.Join(from, "\n"))
	buffer.WriteString("\nreturn out, err\n}\n")
	return buffer.String(), nil
}

// unmappable returns the error for a Go type which cannot be converted.
func unmappable(expr ast.Expr) error {
	return fmt.Errorf("cannot convert type %s", types.ExprString(expr))
}

// messageName returns the name of the generated message that expr is, or false
// if it is not one.
func (g *convGenerator) messageName(expr ast.Expr) (string, bool) {
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return "", false
	}
	_, ok = g.messages[ident.Name]
	return ident.Name, ok
}

// underlying returns the underlying type of the named type name. An error is
// returned for a named type of a message, which is not supported.
func (g *convGenerator) underlying(name string) (ast.Expr, error) {
	expr, err := parser.ParseExpr(g.named[name])
	if err != nil {
		return nil, fmt.Errorf("cannot convert type %s", name)
	}
	if _, ok := g.messageName(expr); ok {
		return nil, fmt.Errorf("cannot convert type %s of a message", name)
	}
	return expr, nil
}

// errCheck is the statements which return from a fromProto function if err is
// set.
var errCheck = []string{"if err != nil {", "return out, err", "}"}

// srcType returns the source form of the Go type expr, with the types of the
// SRPC package qualified by its name. An error is returned if expr is not a
// type that a message field can have.
func (g *convGenerator) srcType(expr ast.Expr) (string, error) {
	switch expr := expr.(type) {
	case *ast.Ident:
		if types.Universe.Lookup(expr.Name) != nil {
			return expr.Name, nil
		}
		return g.typesName + "." + expr.Name, nil
	case *ast.SelectorExpr:
		pkg := types.ExprString(expr.X)
		if _, ok := convImports[pkg]; !ok {
			return "", unmappable(expr)
		}
		g.needs(pkg)
		return types.ExprString(expr), nil
	case *ast.StarExpr:
		elem, err := g.srcType(expr.X)
		return "*" + elem, err
	case *ast.ArrayType:
		elem, err := g.srcType(expr.Elt)
		return "[]" + elem, err
	case *ast.MapType:
		key, err := g.srcType(expr.Key)
		if err != nil {
			return "", err
		}
		value, err := g.srcType(expr.Value)
		return "map[" + key + "]" + value, err
	}
	return "", unmappable(expr)
}

// pbType returns the Go type that protoc-gen-go uses for a field of Go type
// expr. An error is returned if the type has no proto type.
func (g *convGenerator) pbType(expr ast.Expr) (string, error) {
	protoType, err := g.mapper.protoType(expr)
	if err != nil {
		return "", err
	}
	return g.pbGoType(protoType), nil
}

// pbGoType returns the Go type that protoc-gen-go uses for the proto type.
func (g *convGenerator) pbGoType(protoType string) string {
	switch {
	case strings.HasPrefix(protoType, "repeated "):
		return "[]" + g.pbGoType(strings.TrimPrefix(protoType, "repeated "))
	case strings.HasPrefix(protoType, "map<"):
		key, value, _ := strings.Cut(strings.TrimSuffix(
			strings.TrimPrefix(protoType, "map<"), ">"), ", ")
		return "map[" + g.pbGoType(key) + "]" + g.pbGoType(value)
	case protoType == "bytes":
		return "[]byte"
	case protoType == "google.protobuf.Duration":
		g.needs("durationpb")
		return "*durationpb.Duration"
	case protoType == "google.protobuf.Timestamp":
		g.needs("timestamppb")
		return "*timestamppb.Timestamp"
	}
	if goType, ok := scalarGoTypes[protoType]; ok {
		return goType
	}
	return "*pb." + protoType
}

// castType returns the form of the Go type expr for use as a conversion, which
// a pointer type needs in parentheses. An error is returned as for srcType.
func (g *convGenerator) castType(expr ast.Expr) (string, error) {
	srcType, err := g.srcType(expr)
	if strings.HasPrefix(srcType, "*") {
		srcType = "(" + srcType + ")"
	}
	return srcType, err
}

// toProto returns the statements which set dst to the proto form of src, which
// has the Go type expr. level makes the names of nested variables unique. An
// error is returned if the type cannot be converted.
func (g *convGenerator) toProto(dst, src string, expr ast.Expr,
	level int) ([]string, error) {
	switch expr := expr.(type) {
	case *ast.Ident:
		return g.identToProto(dst, src, expr, level)
	case *ast.SelectorExpr:
		return g.selectorToProto(dst, src, expr, level)
	case *ast.StarExpr:
		name, ok := g.messageName(expr.X)
		if !ok {
			return nil, unmappable(expr)
		}
		return []string{fmt.Sprintf("%s = toProto%s(%s)", dst, name, src)},
			nil
	case *ast.ArrayType:
		return g.sliceConv(g.to, dst, src, expr, level)
	case *ast.MapType:
		return g.mapConv(g.to, dst, src, expr, level)
	}
	return nil, unmappable(expr)
}

// identToProto is toProto for a type name, which is a predeclared type, a
// message or a named type, which it follows to its underlying type.
func (g *convGenerator) identToProto(dst, src string, expr *ast.Ident,
	level int) ([]string, error) {
	if mapped, ok := basicProtoType(expr.Name); ok {
		if goType := scalarGoTypes[mapped]; goType != expr.Name {
			src = goType + "(" + src + ")"
		}
		return []string{dst + " = " + src}, nil
	}
	if _, ok := g.messages[expr.Name]; ok {
		return []string{fmt.Sprintf("%s = toProto%s(&%s)", dst, expr.Name,
			src)}, nil
	}
	underlying, err := g.underlying(expr.Name)
	if err != nil {
		return nil, err
	}
	if ident, ok := underlying.(*ast.Ident); ok {
		if mapped, ok := basicProtoType(ident.Name); ok {
			return []string{fmt.Sprintf("%s = %s(%s)", dst,
				scalarGoTypes[mapped], src)}, nil
		}
		return g.identToProto(dst, src, ident, level)
	}
	castType, err := g.castType(underlying)
	if err != nil {
		return nil, err
	}
	return g.toProto(dst, castType+"("+src+")", underlying, level)
}

// wellKnown returns the name and the conversion of the Go type expr from
// another package, and records the packages that the conversion uses. An error
// is returned if there is no conversion for it.
func (g *convGenerator) wellKnown(expr *ast.SelectorExpr) (string,
	wellKnownConv, error) {
	name := types.ExprString(expr)
	conv, ok := wellKnownConvs[name]
	if !ok {
		return "", wellKnownConv{}, unmappable(expr)
	}
	for _, pkg := range conv.imports {
		g.needs(pkg)
	}
	return name, conv, nil
}

// selectorToProto is toProto for a type from another package. A zero time
// which is a field is left unset, but one in a slice or map must be sent.
func (g *convGenerator) selectorToProto(dst, src string,
	expr *ast.SelectorExpr, level int) ([]string, error) {
	name, conv, err := g.wellKnown(expr)
	if err != nil {
		return nil, err
	}
	line := dst + " = " + fmt.Sprintf(conv.to, src)
	if name == timeType && level == 0 {
		return []string{"if !" + src + ".IsZero() {", line, "}"}, nil
	}
	return []string{line}, nil
}

// fromProto returns the statements which set dst to the SRPC form of src,
// which has the proto type for the Go type expr. level makes the names of
// nested variables unique. The statements return from the function if a
// conversion fails.
func (g *convGenerator) fromProto(dst, src string, expr ast.Expr,
	level int) ([]string, error) {
	switch expr := expr.(type) {
	case *ast.Ident:
		return g.identFromProto(dst, src, expr, level)
	case *ast.SelectorExpr:
		return g.selectorFromProto(dst, src, expr, level)
	case *ast.StarExpr:
		return g.pointerFromProto(dst, src, expr, level)
	case *ast.ArrayType:
		return g.sliceConv(g.from, dst, src, expr, level)
	case *ast.MapType:
		return g.mapConv(g.from, dst, src, expr, level)
	}
	return nil, unmappable(expr)
}

// identFromProto is fromProto for a type name, which is a predeclared type, a
// message or a named type, which it follows to its underlying type. A value
// outside the range of a narrow integer type is truncated.
func (g *convGenerator) identFromProto(dst, src string, expr *ast.Ident,
	level int) ([]string, error) {
	if mapped, ok := basicProtoType(expr.Name); ok {
		if scalarGoTypes[mapped] != expr.Name {
			src = expr.Name + "(" + src + ")"
		}
		return []string{dst + " = " + src}, nil
	}
	if _, ok := g.messages[expr.Name]; ok {
		return append([]string{fmt.Sprintf("%s, err = fromProto%s(%s)", dst,
			expr.Name, src)}, errCheck...), nil
	}
	underlying, err := g.underlying(expr.Name)
	if err != nil {
		return nil, err
	}
	srcType, err := g.srcType(expr)
	if err != nil {
		return nil, err
	}
	if ident, ok := underlying.(*ast.Ident); ok {
		if _, ok := basicProtoType(ident.Name); ok {
			return []string{fmt.Sprintf("%s = %s(%s)", dst, srcType, src)},
				nil
		}
	}
	temp := fmt.Sprintf("named%d", level)
	underlyingType, err := g.srcType(underlying)
	if err != nil {
		return nil, err
	}
	inner, err := g.fromProto(temp, src, underlying, level+1)
	if err != nil {
		return nil, err
	}
	lines := append([]string{"{", fmt.Sprintf("var %s %s", temp,
		underlyingType)}, inner...)
	return append(lines, fmt.Sprintf("%s = %s(%s)", dst, srcType, temp),
		"}"), nil
}

// selectorFromProto is fromProto for a type from another package. A time
// which is not set is the zero time.
func (g *convGenerator) selectorFromProto(dst, src string,
	expr *ast.SelectorExpr, level int) ([]string, error) {
	name, conv, err := g.wellKnown(expr)
	if err != nil {
		return nil, err
	}
	if name == timeType {
		value := fmt.Sprintf("value%d", level)
		return []string{"if " + value + " := " + src + "; " + value +
			" != nil {", dst + " = " + fmt.Sprintf(conv.from, value), "}"}, nil
	}
	if conv.fromErr {
		return append([]string{dst + ", err = " + fmt.Sprintf(conv.from, src)},
			errCheck...), nil
	}
	return []string{dst + " = " + fmt.Sprintf(conv.from, src)}, nil
}

// pointerFromProto is fromProto for a pointer to a message. A nil message
// gives a nil pointer.
func (g *convGenerator) pointerFromProto(dst, src string, expr *ast.StarExpr,
	level int) ([]string, error) {
	name, ok := g.messageName(expr.X)
	if !ok {
		return nil, unmappable(expr)
	}
	value := fmt.Sprintf("value%d", level)
	lines := []string{"if " + src + " != nil {",
		fmt.Sprintf("var %s %s.%s", value, g.typesName, name),
		fmt.Sprintf("%s, err = fromProto%s(%s)", value, name, src)}
	lines = append(lines, errCheck...)
	return append(lines, dst+" = &"+value, "}"), nil
}

// sliceConv returns the statements which convert a slice in the direction c.
// A nil or empty slice is left as the zero value. An error is returned if the
// element type cannot be converted.
func (g *convGenerator) sliceConv(c direction, dst, src string,
	expr *ast.ArrayType, level int) ([]string, error) {
	if elem := types.ExprString(expr.Elt); elem == "byte" || elem == "uint8" {
		return []string{dst + " = " + src}, nil
	}
	destElem, err := c.destType(expr.Elt)
	if err != nil {
		return nil, err
	}
	index, item := fmt.Sprintf("i%d", level), fmt.Sprintf("item%d", level)
	inner, err := c.convert(dst+"["+index+"]", item, expr.Elt, level+1)
	if err != nil {
		return nil, err
	}
	lines := []string{"if len(" + src + ") > 0 {",
		fmt.Sprintf("%s = make([]%s, len(%s))", dst, destElem, src),
		fmt.Sprintf("for %s, %s := range %s {", index, item, src)}
	lines = append(lines, inner...)
	return append(lines, "}", "}"), nil
}

// mapConv returns the statements which convert a map in the direction c. A nil
// or empty map is left as the zero value. An error is returned if the key or
// value type cannot be converted.
func (g *convGenerator) mapConv(c direction, dst, src string,
	expr *ast.MapType, level int) ([]string, error) {
	destKey, err := c.destType(expr.Key)
	if err != nil {
		return nil, err
	}
	destValue, err := c.destType(expr.Value)
	if err != nil {
		return nil, err
	}
	key, value := fmt.Sprintf("key%d", level), fmt.Sprintf("value%d", level)
	newKey := fmt.Sprintf("%sKey%d", c.prefix, level)
	newValue := fmt.Sprintf("%sValue%d", c.prefix, level)
	keyLines, err := c.convert(newKey, key, expr.Key, level+1)
	if err != nil {
		return nil, err
	}
	valueLines, err := c.convert(newValue, value, expr.Value, level+1)
	if err != nil {
		return nil, err
	}
	lines := []string{"if len(" + src + ") > 0 {",
		fmt.Sprintf("%s = make(map[%s]%s, len(%s))", dst, destKey, destValue,
			src),
		fmt.Sprintf("for %s, %s := range %s {", key, value, src),
		fmt.Sprintf("var %s %s", newKey, destKey)}
	lines = append(lines, keyLines...)
	lines = append(lines, fmt.Sprintf("var %s %s", newValue, destValue))
	lines = append(lines, valueLines...)
	return append(lines, fmt.Sprintf("%s[%s] = %s", dst, newKey, newValue),
		"}", "}"), nil
}
